                        icon = Icons.Default.Sync,
                        title = "Cloud Sync & Persistence",
                        subtitle = "Chat conversations & extracted memories saved across devices"
                    )
                    Spacer(modifier = Modifier.height(14.dp))
                    FeatureRow(
                        icon = Icons.Default.Lock,
                        title = "Zero-Trust Security",
                        subtitle = "Your companion settings and memories are isolated to your account"
                    )
                    Spacer(modifier = Modifier.height(14.dp))
                    FeatureRow(
                        icon = Icons.Default.AutoAwesome,
                        title = "Personalized Persona",
                        subtitle = "Evolving dynamic memory powered by Firebase & Gemini"
                    )
                }
            }

            Spacer(modifier = Modifier.height(32.dp))

            if (errorMessage != null) {
                Text(
                    text = errorMessage.orEmpty(),
                    color = Color(0xFFFF6B6B),
                    style = MaterialTheme.typography.bodySmall,
                    textAlign = TextAlign.Center,
